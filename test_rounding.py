def configure_logging(filename=None, level=logging.DEBUG):
    if filename:
        handler = WatchedFileHandler(filename, encoding="utf-8")
    else:
        handler = logging.StreamHandler(sys.stdout)
    logging.basicConfig(
        format="%(asctime)s [%(name)s] %(levelname)s: %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
        level=level,
        handlers=[handler],
    )
    logging.getLogger("elasticsearch").setLevel(logging.ERROR)
    logging.captureWarnings(True)


def round_coordinates(geometry, decimals=5):
    """Return geometry with coordinates rounded to given number of decimals.

    See here why we cannot naively round the coordinates:
    https://gis.stackexchange.com/a/276512
    """

    # return shapely.geometry.mapping(
    #     shapely.wkt.loads(
    #         shapely.wkt.dumps(
    #             shapely.geometry.shape(geometry), rounding_precision=decimals
    #         )
    #     )
    # )

    geom = shapely.wkt.loads(
        shapely.wkt.dumps(shapely.geometry.shape(geometry), rounding_precision=decimals)
    )

    if not geom.is_valid:
        logger.error("Method WKT: Invalid geometry")
    else:
        logger.info("Method WKT: Valid geometry")
    return shapely.geometry.mapping(geom)


def round_coordinates_prec(geometry, grid_size=1e-5):
    """Return geometry with coordinates rounded to given precision.

    It uses "valid_output" mode of shapely set_precision method, which:
    - rounds to a maximum precision
    - preserves valid geometry
    - deletes collapsed polygons etc.
    - normalizes rings in polygons

    See:
    https://shapely.readthedocs.io/en/2.0.2/reference/shapely.set_precision.html
    """
    geom = shapely.geometry.shape(geometry)

    mode = "valid_output"
    rounded_geom = shapely.set_precision(geom, grid_size=grid_size, mode=mode)

    if not geom.is_valid:
        logger.error("Method precision: Invalid geometry")
    else:
        logger.info("Method precision: Valid geometry")
    return shapely.geometry.mapping(rounded_geom)


